/** Markdown generators for docs/DSL.md and docs/COMPONENTS.md (from the schema and catalog). */

import { z } from "zod";
import { allSpecs } from "../src/catalog";
import { ACTION_TYPES } from "../src/dsl/actions";
import { canonicalJsonSchema } from "../src/dsl/llm-schema";
import { EASING_NAMES } from "../src/interp/easing";
import { LAYOUTS } from "../src/layout/templates";
import { BOX_ANCHORS } from "../src/math/rect";
import { allSolvers } from "../src/solvers/registry";
import { COLOR_ROLES } from "../src/theme/theme";

type Json = Record<string, unknown>;

const esc = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");

function typeOf(s: Json | undefined): string {
  if (!s) return "any";
  if (typeof s.$ref === "string") {
    const name = s.$ref.replace("#/$defs/", "");
    return `[${name}](#${name.toLowerCase()})`;
  }
  if (Array.isArray(s.enum))
    return s.enum.length > 12
      ? `enum (${s.enum.length} values)`
      : s.enum.map((v) => `\`${JSON.stringify(v)}\``).join(" \\| ");
  if (s.const !== undefined) return `\`${JSON.stringify(s.const)}\``;
  const union = (s.anyOf ?? s.oneOf) as Json[] | undefined;
  if (union) return union.map((u) => typeOf(u)).join(" \\| ");
  if (s.type === "array") return `${typeOf(s.items as Json)}[]`;
  if (s.type === "object" && s.properties) return "object";
  return String(s.type ?? "any");
}

function fieldTable(s: Json): string {
  const props = (s.properties ?? {}) as Record<string, Json>;
  const req = new Set((s.required ?? []) as string[]);
  const rows = Object.entries(props).map(([k, v]) => {
    const def = v.default !== undefined ? `\`${JSON.stringify(v.default)}\`` : "";
    return `| \`${k}\` | ${typeOf(v)} | ${req.has(k) ? "yes" : ""} | ${def} | ${esc(String(v.description ?? ""))} |`;
  });
  return ["| Field | Type | Required | Default | Description |", "|---|---|---|---|---|", ...rows].join("\n");
}

export function dslMarkdown(): string {
  const schema = canonicalJsonSchema();
  const defs = (schema.$defs ?? {}) as Record<string, Json>;
  const out: string[] = [
    "# Scene DSL reference",
    "",
    "> GENERATED by `make codegen` from the engine's Zod schemas. Do not edit by hand.",
    "",
    "A scene is JSON validated by the engine. LLMs write the strict **LLM-facing** form",
    "(`contracts/dsl.llm.schema.json`: every field present, `null` = use the default); `lift()`",
    "turns it into this canonical form. Coordinates are pixels on a 1600x900 canvas, y down.",
    "",
    "## Scene",
    "",
    fieldTable(schema),
    "",
    "## Actions",
    "",
    `\`action\` is one of: ${ACTION_TYPES.map((a) => `\`${a}\``).join(", ")}.`,
    "",
    "Timing: `start` is `{at}` (seconds, `cue:<id>`, `beat:<id>`, `beat_end:<id>`), `{after: <action id>}` or",
    "`{with: <action id>}`, plus optional `delay`. Without `start`, an action begins after the previous one.",
    "",
  ];
  const action = defs.Action as Json | undefined;
  for (const variant of (action?.anyOf ?? action?.oneOf ?? []) as Json[]) {
    const name = ((variant.properties as Record<string, Json>).action?.const as string) ?? "?";
    out.push(`### \`${name}\``, "", fieldTable(variant), "");
  }
  out.push("## Shared types", "");
  for (const [name, def] of Object.entries(defs).sort(([a], [b]) => a.localeCompare(b))) {
    if (name === "Action" || name.startsWith("Object_") || name === "Object") continue;
    out.push(`### ${name}`, "");
    if (def.description) out.push(String(def.description), "");
    const union = (def.anyOf ?? def.oneOf) as Json[] | undefined;
    if (def.properties) out.push(fieldTable(def), "");
    else if (union) {
      union.forEach((u, i) => {
        out.push(u.properties ? `Variant ${i + 1}:\n\n${fieldTable(u)}\n` : `- ${typeOf(u)}`);
      });
      out.push("");
    } else out.push(`Type: ${typeOf(def)}`, "");
  }
  out.push(
    "## Vocabularies",
    "",
    `**Color roles** (add \`.light\`, \`.dark\` or \`.soft\`): ${COLOR_ROLES.map((c) => `\`${c}\``).join(", ")}.`,
    "",
    `**Easings**: ${EASING_NAMES.map((e) => `\`${e}\``).join(", ")}, or \`{ "cubic_bezier": [x1, y1, x2, y2] }\`.`,
    "",
    `**Box anchors** (every object): ${BOX_ANCHORS.map((a) => `\`${a}\``).join(", ")}.`,
    "",
    "**Layouts and slots**:",
    "",
    ...Object.values(LAYOUTS).map(
      (l) =>
        `- \`${l.id}\`: ${Object.keys(l.slots)
          .map((s) => `\`${s}\``)
          .join(", ")}`,
    ),
    "",
    "**Solvers** (outputs are bindable as `<solver id>.<output>`):",
    "",
    ...allSolvers().map((s) => `- \`${s.type}\`: ${s.outputs.map((o) => `\`${o.name}\` (${o.unit})`).join(", ")}`),
    "",
  );
  return out.join("\n");
}

export function componentsMarkdown(): string {
  const out: string[] = [
    "# Component catalog",
    "",
    "> GENERATED by `make codegen` from the engine's component specs. Do not edit by hand.",
    "",
    "Every object's `type` is one of these. Params are validated per type; unknown params are errors.",
    "",
  ];
  const byCat = new Map<string, ReturnType<typeof allSpecs>>();
  for (const s of allSpecs().filter((x) => !x.hidden)) byCat.set(s.category, [...(byCat.get(s.category) ?? []), s]);
  for (const [cat, specs] of byCat) {
    out.push(`## ${cat}`, "");
    for (const s of specs) {
      const params = z.toJSONSchema(s.params, { io: "input", unrepresentable: "any" }) as Json;
      out.push(`### \`${s.type}\``, "", s.description, "");
      const caps = [
        s.draw && "draw",
        s.write && "write",
        s.worldSpace && "positioned by endpoints",
        s.labelLike && "label-like",
      ].filter(Boolean);
      out.push(`Entrance: \`${s.entrance}\`${caps.length ? ` · Supports: ${caps.join(", ")}` : ""}`, "");
      if (s.anchors?.length) out.push(`Anchors (plus box anchors): ${s.anchors.map((a) => `\`${a}\``).join(", ")}`, "");
      out.push(fieldTable(params), "");
      if (s.examples[0]) out.push("```json", JSON.stringify(s.examples[0]), "```", "");
    }
  }
  return out.join("\n");
}
