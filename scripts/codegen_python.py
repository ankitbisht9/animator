"""Generate the Python side of `contracts/` from the engine's JSON Schemas.

Run through `make codegen` (after the TypeScript codegen). Output is committed and
CI fails if regenerating produces a diff.
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONTRACTS = ROOT / "contracts"
PKG = CONTRACTS / "python" / "src" / "animator_contracts"

HEADER = "# GENERATED by scripts/codegen_python.py from contracts/. Do not edit; run `make codegen`.\n"


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {path.relative_to(ROOT).as_posix()}")


def gen_version() -> None:
    manifest = json.loads((CONTRACTS / "engine.json").read_text(encoding="utf-8"))
    write(
        PKG / "_version.py",
        HEADER
        + f'PROTOCOL_VERSION = "{manifest["protocolVersion"]}"\n'
        + f'ENGINE_VERSION = "{manifest["engineVersion"]}"\n'
        + f'DSL_VERSION = "{manifest["dslVersion"]}"\n',
    )


def gen_protocol_models() -> None:
    schema = CONTRACTS / "protocol.schema.json"
    if not schema.exists():
        return
    out = PKG / "protocol.py"
    subprocess.run(
        [
            sys.executable,
            "-m",
            "datamodel_code_generator",
            "--input",
            str(schema),
            "--input-file-type",
            "jsonschema",
            "--output",
            str(out),
            "--output-model-type",
            "pydantic_v2.BaseModel",
            "--target-python-version",
            "3.13",
            "--use-standard-collections",
            "--use-union-operator",
            "--use-schema-description",
            "--use-field-description",
            "--disable-timestamp",
            "--enum-field-as-literal",
            "all",
            "--use-title-as-name",
            "--custom-file-header",
            HEADER.rstrip("\n"),
        ],
        check=True,
    )
    # Normalize line endings so Windows and Linux produce byte-identical output.
    out.write_text(out.read_text(encoding="utf-8"), encoding="utf-8", newline="\n")
    print(f"wrote {out.relative_to(ROOT).as_posix()}")


if __name__ == "__main__":
    gen_version()
    gen_protocol_models()
